import { staffRequest } from '../shared/staffRequest.js'
const request = (path, options) => staffRequest('/api/superadmin', path, options)

export const getSuperOverview = () => request('/overview')
export const getSuperStaff = () => request('/me')
export const loginSuperadmin = (email, password, otp, factorId) => request('/login', { method: 'POST', body: { email, password, otp, factorId } })
export const logoutSuperadmin = () => request('/logout', { method: 'POST' })
export const getTeam = ({ page = 1, search = '' } = {}) => request(`/team?page=${page}&search=${encodeURIComponent(search)}`)
export const lookupTeamEmail = (email) => request(`/team/lookup?email=${encodeURIComponent(email)}`)
export const getActivity = () => request('/activity')
export const changeRole = (id, expectedRole, role, note) => request(`/team/${encodeURIComponent(id)}/role`, { method: 'POST', body: { expectedRole, role, note } })
export const decideRoleApproval = (id, decision) => request(`/approvals/${encodeURIComponent(id)}/decision`, { method: 'POST', body: { decision } })
export const getRefundApprovals = () => request('/refunds')
export const decideRefundApproval = (id, decision, note) => request(`/refunds/${encodeURIComponent(id)}/decision`, { method: 'POST', body: { decision, note } })
export const getPlatformMetrics = () => request('/metrics')
export const getPrivacyQueue = () => request('/privacy')
export const closeStudentAccount = (studentId, note) => request(`/privacy/${encodeURIComponent(studentId)}/close`, { method: 'POST', body: { note } })
export const getEmailOutbox = () => request('/email-outbox')
export const retryEmail = (id) => request(`/email-outbox/${encodeURIComponent(id)}/retry`, { method: 'POST' })
export const reconcilePayments = () => request('/payments/reconcile', { method: 'POST' })

export const getGovernance = () => request('/governance')
export const revokeStaffSession = (id) => request(`/sessions/${encodeURIComponent(id)}`, { method: 'DELETE' })
export const createLegalHold = (subjectId, reason) => request('/legal-holds', { method: 'POST', body: { subjectId, reason } })
export const releaseLegalHold = (id, reason) => request(`/legal-holds/${encodeURIComponent(id)}/release`, { method: 'POST', body: { reason } })
export const publishPolicy = (kind, version, content) => request('/policies', { method: 'POST', body: { kind, version, content } })
export const runRetention = () => request('/retention/run', { method: 'POST' })

export const removeEmailSuppression = (id) => request(`/email-suppressions/${encodeURIComponent(id)}`, { method: 'DELETE' })
