import { staffRequest } from '../shared/staffRequest.js'
const request = (path, options) => staffRequest('/api/admin', path, options)

export const getStaff = () => request('/me')
export const loginStaff = (email, password, otp, factorId) => request('/login', { method: 'POST', body: { email, password, otp, factorId } })
export const logoutStaff = () => request('/logout', { method: 'POST' })
export const getOverview = () => request('/overview')
export const getConversations = () => request('/conversations')
export const getConversation = (id) => request(`/conversations/${encodeURIComponent(id)}/messages`)
export const sendConversationReply = (id, body) => request(`/conversations/${encodeURIComponent(id)}/messages`, { method: 'POST', body: { body } })
export const markConversationRead = (id) => request(`/conversations/${encodeURIComponent(id)}/read`, { method: 'POST' })
export const getCase = (id) => request(`/tasks/${encodeURIComponent(id)}`)
export const recordReview = (id, action, note) => request(`/tasks/${encodeURIComponent(id)}/review`, { method: 'POST', body: { action, note } })
export const issuePlan = (id, plan) => request(`/tasks/${encodeURIComponent(id)}/plan`, { method: 'POST', body: plan })
export const issueScopeChange = (id, change) => request(`/tasks/${encodeURIComponent(id)}/scope-change`, { method: 'POST', body: change })
export const getAssignableExperts = () => request('/experts')
export const reviewExpert = (id, decision, note) => request(`/experts/${encodeURIComponent(id)}/review`, { method: 'POST', body: { decision, note } })
export const assignExpert = (id, expertId) => request(`/tasks/${encodeURIComponent(id)}/assign`, { method: 'POST', body: { expertId } })
export const getSupportQueue = () => request('/support')
export const getSupportCase = (id) => request(`/support/${encodeURIComponent(id)}`)
export const updateSupportStatus = (id, status, note, studentMessage, priority, assignToMe) => request(`/support/${encodeURIComponent(id)}/status`, { method: 'POST', body: { status, note, studentMessage, priority, assignToMe } })
export const getQaQueue = () => request('/qa')
export const getQaCase = (id) => request(`/qa/${encodeURIComponent(id)}`)
export const recordQaOutcome = (id, outcome, note) => request(`/qa/${encodeURIComponent(id)}/outcome`, { method: 'POST', body: { outcome, note } })
export const getRefundQueue = () => request('/refunds')
export const decideRefund = (id, decision, note, completedWorkReview = false) => request(`/refunds/${encodeURIComponent(id)}/decision`, { method: 'POST', body: { decision, note, completedWorkReview } })
export const getPayoutQueue = () => request('/payouts')
export const decidePayout = (id, status, note, reference) => request(`/payouts/${encodeURIComponent(id)}/decision`, { method: 'POST', body: { status, note, reference } })
export const getOpportunityInterests = () => request('/opportunities/interests')
export const publishOpportunity = (opportunity) => request('/opportunities', { method: 'POST', body: opportunity })

export const getSolvyJobs = () => request('/solvy-jobs')
export const retrySolvyJob = (id) => request(`/solvy-jobs/${encodeURIComponent(id)}/retry`, { method: 'POST' })
export const getPaymentOperations = () => request('/payments')
export const updatePaymentDispute = (id, status, note) => request(`/payments/${encodeURIComponent(id)}/dispute`, { method: 'POST', body: { status, note } })

export const getExpertRequests = () => request('/expert-requests')
export const decideExpertRequest = (id, decision, note) => request(`/expert-requests/${encodeURIComponent(id)}/decision`, { method: 'POST', body: { decision, note } })
